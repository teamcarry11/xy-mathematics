// Font renderer: renders text using bitmap font.
pub const FontRenderer = struct {
    renderer: *const framebuffer_renderer.FramebufferRenderer,

    pub fn init(renderer: *const framebuffer_renderer.FramebufferRenderer) FontRenderer {
        std.debug.assert(@intFromPtr(renderer) != 0);
        return FontRenderer{
            .renderer = renderer,
        };
    }

    // Draw a single character at position (x, y).
    // 2025-11-26-130343-pst: Active function
    pub fn draw_char(
        self: *const FontRenderer,
        ch: u8,
        x: u32,
        y: u32,
        fg_color: u32,
    ) void {
        std.debug.assert(x < framebuffer_renderer.FRAMEBUFFER_WIDTH);
        std.debug.assert(y < framebuffer_renderer.FRAMEBUFFER_HEIGHT);
        // Only render printable ASCII (32-126).
        if (ch < 32 or ch > 126) {
            return;
        }
        const char_index = ch - 32;
        const font_char = FONT_DATA[char_index];
        var row: u32 = 0;
        while (row < FONT_HEIGHT) : (row += 1) {
            const font_row = font_char[row];
            var col: u32 = 0;
            while (col < FONT_WIDTH) : (col += 1) {
                const bit_mask: u8 = @as(u8, 1) << @as(u3, @intCast(7 - col));
                if (font_row & bit_mask != 0) {
                    const px = x + col;
                    const py = y + row;
                    if (px < framebuffer_renderer.FRAMEBUFFER_WIDTH and
                        py < framebuffer_renderer.FRAMEBUFFER_HEIGHT)
                    {
                        self.renderer.draw_pixel(px, py, fg_color);
                    }
                }
            }
        }
    }

    // Draw text string at position (x, y).
    // 2025-11-26-130343-pst: Active function
    pub fn draw_text(
        self: *const FontRenderer,
        text: []const u8,
        x: u32,
        y: u32,
        fg_color: u32,
    ) void {
        std.debug.assert(text.len > 0);
        std.debug.assert(text.len <= MAX_TEXT_LEN);
        std.debug.assert(x < framebuffer_renderer.FRAMEBUFFER_WIDTH);
        std.debug.assert(y < framebuffer_renderer.FRAMEBUFFER_HEIGHT);
        var char_x = x;
        var i: u32 = 0;
        while (i < text.len) : (i += 1) {
            const ch = text[i];
            self.draw_char(ch, char_x, y, fg_color);
            char_x += FONT_WIDTH;
            // Stop if we would exceed framebuffer width.
            if (char_x + FONT_WIDTH > framebuffer_renderer.FRAMEBUFFER_WIDTH) {
                break;
            }
        }
    }
};

